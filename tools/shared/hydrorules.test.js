const R = require("./hydrorules.js");
let pass = 0, fail = 0;
const t = (name, got, want) => { if (JSON.stringify(got) === JSON.stringify(want)) pass++; else { fail++; console.log("FAIL", name, "got", got, "want", want); } };
const w = R.ruleFor("water", "hydro"), a = R.ruleFor("water", "air"), h = R.ruleFor("heat", "hydro");
const base = { work: 4, testP: 6, start: 6, end: 6, minutes: 30, leak: "no", cond: { noFixtures: true, temp: true } };
t("water ok", R.evaluate(w, base).status, R.ST.OK);
t("water drop 0.2 ok", R.evaluate(w, { ...base, end: 5.8 }).status, R.ST.OK);
t("water drop 0.3 bad", R.evaluate(w, { ...base, end: 5.7 }).status, R.ST.BAD);
t("water 29 min bad", R.evaluate(w, { ...base, minutes: 29 }).status, R.ST.BAD);
t("water leak bad", R.evaluate(w, { ...base, leak: "yes" }).status, R.ST.BAD);
t("water no leak data", R.evaluate(w, { ...base, leak: null }).status, R.ST.NODATA);
t("water no end", R.evaluate(w, { ...base, end: null }).status, R.ST.NODATA);
t("water 9 bar out of range", R.evaluate(w, { ...base, work: 6, testP: 9, start: 9, end: 9 }).status, R.ST.RANGE);
t("water 0.5 bar out of range", R.evaluate(w, { ...base, work: 0.3, testP: 0.5, start: 0.5, end: 0.5 }).status, R.ST.RANGE);
t("water 6.5 edge ok", R.evaluate(w, { ...base, work: 4.33, testP: 6.5, start: 6.5, end: 6.5 }).status, R.ST.OK);
t("water below required bad", R.evaluate(w, { ...base, work: 6, testP: 6, start: 6, end: 6 }).status, R.ST.BAD);
t("water above required confirm", R.evaluate(w, { ...base, work: 3, testP: 6, start: 6, end: 6 }).status, R.ST.CONFIRM);
t("water cond missing", R.evaluate(w, { ...base, cond: { temp: true } }).status, R.ST.CONFIRM);
t("water glued needs wait24", R.evaluate(w, { ...base, glued: true }).status, R.ST.CONFIRM);
t("water glued with wait24", R.evaluate(w, { ...base, glued: true, cond: { noFixtures: true, temp: true, wait24: true } }).status, R.ST.OK);
t("comp limit", R.evaluate(w, { ...base, compMax: 5 }).status, R.ST.RANGE);
t("required 1.5x", R.required(w, 4), 6);
const air = { start: 1, end: 0.9, minutes: 5, leak: "no", air1: true, cond: { noFixtures: true, temp: true } };
t("air ok", R.evaluate(a, air).status, R.ST.OK);
t("air drop 0.1 ok", R.evaluate(a, air).drop, 0.1);
t("air drop 0.2 bad", R.evaluate(a, { ...air, end: 0.8 }).status, R.ST.BAD);
t("air 4 min bad", R.evaluate(a, { ...air, minutes: 4 }).status, R.ST.BAD);
t("air stage1 missing", R.evaluate(a, { ...air, air1: false }).status, R.ST.CONFIRM);
t("air control not 1.0", R.evaluate(a, { ...air, start: 1.5, end: 1.5 }).status, R.ST.CONFIRM);
t("air out of range", R.evaluate(a, { ...air, start: 3.5, end: 3.5 }).status, R.ST.RANGE);
t("air 1.5 is not control", R.evaluate(a, { ...air, start: 1.5, end: 1.4 }).status, R.ST.CONFIRM);
const he = { work: 4, testP: 5.2, start: 5.2, end: 5.0, minutes: 120, leak: "no", cond: { temp: true }, confirm: true };
t("heat ok with confirm (drop not judged)", R.evaluate(h, he).status, R.ST.OK);
t("heat no auto tolerance big drop still ok-by-confirm", R.evaluate(h, { ...he, end: 3 }).status, R.ST.OK);
t("heat no confirm", R.evaluate(h, { ...he, confirm: false }).status, R.ST.CONFIRM);
t("heat 119 min bad", R.evaluate(h, { ...he, minutes: 119 }).status, R.ST.BAD);
t("heat leak bad", R.evaluate(h, { ...he, leak: "yes" }).status, R.ST.BAD);
t("heat required 1.3x", R.required(h, 4), 5.2);
t("heat comp limit", R.evaluate(h, { ...he, compMax: 5 }).status, R.ST.RANGE);
t("heat has note", R.evaluate(h, he).notes.length, 1);
t("heat 9 bar no range limit", R.evaluate(h, { ...he, work: 6.9, testP: 9, start: 9, end: 9 }).status, R.ST.OK);
t("negative", R.evaluate(w, { ...base, start: -1, testP: -1 }).status, R.ST.RANGE);
t("no rule", R.evaluate(null, {}).status, R.ST.NODATA);
t("maxDrop heat null", h.maxDrop, null);
console.log(pass + " passed, " + fail + " failed");
process.exit(fail ? 1 : 0);
